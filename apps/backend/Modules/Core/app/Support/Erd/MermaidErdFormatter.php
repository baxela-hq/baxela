<?php

namespace Modules\Core\Support\Erd;

use Illuminate\Support\Str;

/**
 * Pure renderer: ErdDocument → markdown pages with Mermaid erDiagram blocks.
 * No I/O, fully deterministic (sorted everywhere, no timestamps), so output
 * is byte-stable for erd:generate --check.
 *
 * Edge semantics: solid "--" = enforced database FK, dashed ".." = Eloquent
 * relation without a DB FK — regardless of module boundaries.
 */
class MermaidErdFormatter
{
    protected const string HEADER = '<!-- Generated by `php artisan erd:generate` — do not edit. Regenerate after schema changes. -->';

    public function formatIndex(ErdDocument $document): string
    {
        $moduleRows = [];
        foreach ($document->modules() as $module) {
            $counts = $document->countsFor($module);
            $moduleRows[] = sprintf(
                '| [%s](%s.md) | %d | %d | %d | %d |',
                $this->displayName($module),
                $this->fileName($module),
                count($document->tablesFor($module)),
                $counts['fk'],
                $counts['app'],
                $counts['unresolved'],
            );
        }

        $dependencyLines = [];
        foreach ($document->dependencies as [$from, $to]) {
            $dependencyLines[] = '    '.Str::lower($from).' --> '.Str::lower($to);
        }

        $lines = [
            self::HEADER,
            '',
            '# Database ERD',
            '',
            sprintf(
                '%d tables across %d modules. Regenerate with `php artisan erd:generate`.',
                count($document->tables),
                count($document->modules()),
            ),
            '',
            '| Module | Tables | FK edges | App-level edges | Unresolved refs |',
            '|---|---:|---:|---:|---:|',
            ...$moduleRows,
            '',
            '## Module dependencies (cross-module references)',
            '',
            '```mermaid',
            'graph LR',
            ...($dependencyLines ?: ['    %% no cross-module edges found']),
            '```',
            '',
            '> **Legend** — solid `--`: enforced database FK · dashed `..`: Eloquent relation without a DB FK.',
            '',
        ];

        return implode("\n", $lines);
    }

    public function formatModule(string $module, ErdDocument $document): string
    {
        $tables = $document->tablesFor($module);
        ksort($tables);

        $edges = $document->edgesTouching($tables);
        $morphNotes = $document->morphNotesFor($tables);
        $unresolved = $document->unresolvedFor($tables);
        $counts = $document->countsFor($module);

        $lines = [
            self::HEADER,
            '',
            '# '.$this->displayName($module),
            '',
            sprintf(
                '%d %s · FK edges: %d · app-level edges: %d · polymorphic: %d',
                count($tables),
                Str::plural('table', count($tables)),
                $counts['fk'],
                $counts['app'],
                count($morphNotes),
            ),
            '',
            '> **Legend** — solid `--`: enforced database FK · dashed `..`: Eloquent relation without a DB FK.',
            '> `PK` primary · `FK` foreign key (arrow shows target) · `UK` unique.',
            '',
            '```mermaid',
            'erDiagram',
        ];

        $foreignColumns = $this->foreignColumnsByTable($edges);

        foreach ($tables as $table) {
            $block = $this->entityBlock($table, $foreignColumns);
            if ($block !== []) {
                $lines = [...$lines, ...$block];
            }
        }

        $lines = [...$lines, ...$this->externalComments($edges, $tables, $document), ...$this->edgeLines($edges)];

        $lines[] = '```';

        if ($morphNotes !== []) {
            $lines[] = '';
            $lines[] = '### Polymorphic relations';
            $lines[] = '';
            $lines[] = '| Table | Columns | Possible targets |';
            $lines[] = '|---|---|---|';
            foreach ($morphNotes as $note) {
                $lines[] = sprintf(
                    '| `%s` | `%s`, `%s` | %s |',
                    $note->table,
                    $note->typeColumn,
                    $note->idColumn,
                    $note->targets !== null ? implode(', ', $note->targets).' (morph map)' : 'dynamic',
                );
            }
        }

        if ($unresolved !== []) {
            $lines[] = '';
            $lines[] = '### Unresolved reference columns';
            $lines[] = '';
            $lines[] = 'Reference-looking columns with neither a DB FK nor an Eloquent relation — cross-module references resolved via gateways at runtime. Targets inferred from naming, **not verified**:';
            $lines[] = '';
            foreach ($unresolved as $key => $hint) {
                $lines[] = $hint === null
                    ? sprintf('- `%s`', $key)
                    : sprintf('- `%s` → `%s`?', $key, $hint);
            }
        }

        $lines[] = '';

        return implode("\n", $lines);
    }

    public function fileName(string $module): string
    {
        return Str::lower($module);
    }

    protected function displayName(string $module): string
    {
        return $module === ModuleTableResolver::OTHER ? 'Other' : Str::title($module);
    }

    /**
     * Map of table => [column => target table] for FK badge comments.
     *
     * @param  array<int, ErdEdge>  $edges
     * @return array<string, array<string, string>>
     */
    protected function foreignColumnsByTable(array $edges): array
    {
        $map = [];
        foreach ($edges as $edge) {
            if ($edge->kind !== ErdEdge::KIND_FK) {
                continue;
            }

            foreach ($edge->columns as $column) {
                $map[$edge->fromTable][$column] ??= $edge->toTable;
            }
        }

        return $map;
    }

    /**
     * @param  array<string, array<string, string>>  $foreignColumns
     * @return array<int, string>
     */
    protected function entityBlock(TableInfo $table, array $foreignColumns): array
    {
        if ($table->columns === []) {
            return ['    %% '.$table->table.' has no introspected columns'];
        }

        $lines = ['    '.$table->table.' {'];

        $commentedTargets = [];
        foreach ($table->columns as $column) {
            $keys = [];

            if ($table->isPrimaryKeyColumn($column->name)) {
                $keys[] = 'PK';
            }

            $comment = null;

            if (isset($foreignColumns[$table->table][$column->name])) {
                $keys[] = 'FK';

                $target = $foreignColumns[$table->table][$column->name];
                if (! in_array($target, $commentedTargets, true)) {
                    $commentedTargets[] = $target;
                    $comment = '→ '.$this->escapeComment($target);
                }
            } elseif ($table->isUniqueColumn($column->name) && ! $table->isPrimaryKeyColumn($column->name)) {
                $keys[] = 'UK';
            }

            $line = '        '.$column->mermaidType().' '.$column->name;

            if ($keys !== []) {
                $line .= ' '.implode(', ', $keys);
            }

            if ($comment !== null) {
                $line .= ' "'.$comment.'"';
            }

            $lines[] = $line;
        }

        $lines[] = '    }';

        return $lines;
    }

    /**
     * Comments marking edge endpoints that are not defined on this page.
     *
     * @param  array<int, ErdEdge>  $edges
     * @param  array<string, TableInfo>  $tables
     * @return array<int, string>
     */
    protected function externalComments(array $edges, array $tables, ErdDocument $document): array
    {
        $externals = [];
        foreach ($edges as $edge) {
            foreach ([$edge->fromTable, $edge->toTable] as $endpoint) {
                if (! isset($tables[$endpoint])) {
                    $owner = $document->moduleOf($endpoint) ?? 'unknown';
                    $externals[$endpoint.' (owned by '.$owner.')'] = true;
                }
            }
        }

        if ($externals === []) {
            return [];
        }

        $lines = ['    %% external tables:'];
        foreach (array_keys($externals) as $external) {
            $lines[] = '    %% '.$external;
        }

        return $lines;
    }

    /**
     * @param  array<int, ErdEdge>  $edges
     * @return array<int, string>
     */
    protected function edgeLines(array $edges): array
    {
        $lines = [];
        foreach ($edges as $edge) {
            $lines[] = '    '.$edge->fromTable.' '.$this->cardinality($edge).' '.$edge->toTable.' : "'.$this->escapeComment($this->edgeLabel($edge)).'"';
        }

        return $lines;
    }

    protected function cardinality(ErdEdge $edge): string
    {
        $line = $edge->kind === ErdEdge::KIND_FK ? '--' : '..';

        return match (true) {
            $edge->unique && $edge->nullable => '|o'.$line.'o|',
            $edge->unique => '||'.$line.'o|',
            $edge->nullable => '}o'.$line.'o|',
            default => '}o'.$line.'||',
        };
    }

    protected function edgeLabel(ErdEdge $edge): string
    {
        $label = implode(', ', $edge->columns);

        if ($edge->foreignColumns !== ['id']) {
            $label .= ' → '.implode(', ', $edge->foreignColumns);
        }

        return $label;
    }

    protected function escapeComment(string $comment): string
    {
        return str_replace('"', "'", $comment);
    }
}
